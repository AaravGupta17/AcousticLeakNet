"""
fig_mendeley_e4.py — Figure 2: real-data (Mendeley Looped) AUROC for the
original model across checkpoints/scaling, vs. loudness-only and GCC-PHAT
baselines, for the CJSJ manuscript.

Reads ONLY the already-committed E4 run record (no model loaded, no data
touched, nothing re-evaluated):
  results/runs/2026-09-23_202146_e4_mendeley_eval.json

This replaces plots/exp2_mendeley_eval.png as the Fig. 2 source: that plot
was generated by the older model_C/mendely_exp_2.py, which (a) predates the
23 Sep E4 rerun this manuscript cites and (b) plots sigmoid probabilities
rather than logits, exactly the saturation artifact AGENTS.md's metric rule
warns against. This script only reads E4's own logit-based AUROC numbers.

    python experiments/fig_mendeley_e4.py
"""
import json

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from _common import PLOTS_DIR, REPO_ROOT

RUN_FILE = REPO_ROOT / "results" / "runs" / "2026-09-23_202146_e4_mendeley_eval.json"
MODEL_LABELS = {
    "best_model_c_v4.pt": "Model C (v4)",
    "best_model_c_seed42.pt": "Model C (seed 42)",
    "best_model_d.pt": "Model D",
    "best_model_mend.pt": "Model (Mendeley-tuned)",
}
NORM_LABELS = {"zscore": "z-score scaling", "fixed": "fixed reference scaling"}


def load():
    data = json.loads(RUN_FILE.read_text())["results"]
    bars = []
    for ckpt, label in MODEL_LABELS.items():
        for norm, norm_label in NORM_LABELS.items():
            r = data["models"][ckpt][norm]["clean_looped"]
            bars.append((f"{label}\n({norm_label})", r["auroc"], r["ci95"]["auroc"]))
    for base_key, base_label in (("rms", "RMS loudness"), ("gcc_peak", "GCC-PHAT peak")):
        r = data["baselines"][base_key]["clean_looped"]
        bars.append((base_label, r["auroc"], r["ci95"]["auroc"]))
    return bars


def main():
    bars = load()
    labels = [b[0] for b in bars]
    aurocs = [b[1] for b in bars]
    los = [b[1] - b[2][0] for b in bars]
    his = [b[2][1] - b[1] for b in bars]
    is_baseline = [i >= len(bars) - 2 for i in range(len(bars))]
    colors = ["steelblue" if not b else "gray" for b in is_baseline]

    fig, ax = plt.subplots(figsize=(9, 5.5))
    y = range(len(bars))
    ax.barh(y, aurocs, xerr=[los, his], color=colors, capsize=4, height=0.6)
    ax.axvline(0.5, color="black", linestyle="--", linewidth=1, label="Chance (0.5)")
    ax.set_yticks(list(y))
    ax.set_yticklabels(labels, fontsize=8)
    ax.invert_yaxis()
    ax.set_xlim(0.0, 1.0)
    ax.set_xlabel("AUROC on Mendeley Looped, clean real recordings (95% CI over recordings)")
    ax.set_title("Zero-shot real-data transfer (E4): AUROC on logits\n"
                  "vs. loudness-only and GCC-PHAT baselines", fontsize=10)
    ax.legend(loc="lower right", fontsize=8)
    plt.tight_layout()
    out = PLOTS_DIR / "fig2_e4_mendeley_auroc.png"
    plt.savefig(out, dpi=150)
    plt.close()
    print(f"Wrote {out}")
    for label, auroc, ci in bars:
        print(f"  {label.replace(chr(10), ' ')}: {auroc:.3f} {ci}")


if __name__ == "__main__":
    main()
